/** FDA shortage status (from the database, in English) -> a translation key. */
export function shortageKey(status: string): Key {
  if (status === "in shortage") return "st_in_shortage";
  if (status.startsWith("on FDA shortage list")) return "st_listed_available";
  if (status.startsWith("shortage resolved")) return "st_resolved";
  if (status.startsWith("not found on FDA")) return "st_not_listed";
  return "st_unknown";
}
